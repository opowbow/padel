function buildSheetMatch(params: {
  id: string;
  round: string;
  timeSlot: string;
  courtName: string;
  a1: Player;
  a2: Player;
  b1: Player;
  b2: Player;
  scoreA: number;
  scoreB: number;
}): RecordedMatch {
  const winnerTeam: 'A' | 'B' | 'Tie' =
    params.scoreA > params.scoreB ? 'A' : params.scoreB > params.scoreA ? 'B' : 'Tie';

  const breakdown = calculateMatchScoring({
    teamAPlayer1: params.a1,
    teamAPlayer2: params.a2,
    teamBPlayer1: params.b1,
    teamBPlayer2: params.b2,
    teamAPointsWon: params.scoreA,
    teamBPointsWon: params.scoreB,
    winnerTeam,
    useWeighting: false,
  });

  return {
    id: params.id,
    sessionId: 'session-spreadsheet-1',
    leagueId: 'league-winter-slay',
    date: '', // No sample date — only spreadsheet Round & Time (user can assign a date anytime)
    round: params.round,
    timeSlot: params.timeSlot,
    courtName: params.courtName,
    teamA: {
      player1: params.a1,
      player2: params.a2,
      setsWon: winnerTeam === 'A' ? 1 : 0,
      pointsWon: params.scoreA,
    },
    teamB: {
      player1: params.b1,
      player2: params.b2,
      setsWon: winnerTeam === 'B' ? 1 : 0,
      pointsWon: params.scoreB,
    },
    setScores: [`${params.scoreA}-${params.scoreB}`],
    winnerTeam,
    weightedBonusApplied: false,
    scoringBreakdown: breakdown,
  };
}

